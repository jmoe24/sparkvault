#!/usr/bin/env python3
"""Fill your host's values into docker-compose.yml. The repo's file stays the single source.

    scripts/make-compose.py --values deploy.conf --out /mnt/share/sparkvault/docker-compose.yaml          # diff only
    scripts/make-compose.py --values deploy.conf --out /mnt/share/sparkvault/docker-compose.yaml --apply  # write it
    scripts/make-compose.py --values deploy.conf --out /mnt/share/sparkvault/docker-compose.yaml --check  # exit 1 on drift

Only lines marked `# @sv <name>` in the template are rewritten (user, hf_dir, port); everything else is copied
byte for byte, and the script refuses to run if a marked line no longer has the shape it expects. Values are
validated strictly because they end up in a YAML file: no quotes, spaces, colons in paths, or newlines.
Dry run by default, like the other sync scripts. An existing output file is kept as <name>.bak when it changes.
Stdlib only.
"""
import argparse
import difflib
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TEMPLATE = HERE.parent / "docker-compose.yml"
MARK = re.compile(r"^(?P<indent>\s*)(?P<body>.*?)\s*# @sv (?P<name>[a-z_]+)\s*$")

# name -> (shape the template line must have, how to write it, how to validate the value)
FIELDS = {
    "user": (re.compile(r'^user: "\d+:\d+"$'), 'user: "{v}"', re.compile(r"^\d{1,10}:\d{1,10}$")),
    "port": (re.compile(r'^- "\d+:8080"$'), '- "{v}:8080"', re.compile(r"^\d{1,5}$")),
    "hf_dir": (re.compile(r"^- /[^:\s\"']+:/hf:ro$"), "- {v}:/hf:ro", re.compile(r"^/[A-Za-z0-9._@+/-]+$")),
}
HEADER = "# GENERATED by scripts/make-compose.py from docker-compose.yml and {vals}. Edit those, not this file.\n"


def read_values(path: Path) -> dict:
    out = {}
    for n, raw in enumerate(path.read_text().splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if "=" not in line:
            sys.exit(f"{path}:{n}: expected `key = value`")
        k, v = (x.strip() for x in line.split("=", 1))
        if k not in FIELDS:
            sys.exit(f"{path}:{n}: unknown key {k!r} (known: {', '.join(FIELDS)})")
        if k in out:
            sys.exit(f"{path}:{n}: {k!r} given twice")
        if not FIELDS[k][2].match(v):
            sys.exit(f"{path}:{n}: bad value for {k!r}")
        if k == "port" and not 1 <= int(v) <= 65535:
            sys.exit(f"{path}:{n}: port must be 1-65535")
        out[k] = v
    return out


def render(template: str, values: dict, vals_name: str) -> str:
    seen, lines = set(), []
    for raw in template.splitlines(keepends=True):
        m = MARK.match(raw.rstrip("\n"))
        if not m:
            lines.append(raw)
            continue
        name = m["name"]
        if name not in FIELDS:
            sys.exit(f"template marks an unknown setting {name!r}")
        shape, fmt, _ = FIELDS[name]
        if not shape.match(m["body"]):
            sys.exit(f"template line for {name!r} no longer has the expected shape: {m['body']!r}")
        seen.add(name)
        body = fmt.format(v=values[name]) if name in values else m["body"]
        lines.append(f"{m['indent']}{body}".ljust(34) + f"  # @sv {name}\n")
    missing = set(FIELDS) - seen
    if missing:
        sys.exit(f"template has no marked line for: {', '.join(sorted(missing))}")
    return HEADER.format(vals=vals_name) + "".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--values", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--template", type=Path, default=TEMPLATE)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--apply", action="store_true")
    g.add_argument("--check", action="store_true", help="exit 1 if --out differs from what would be generated")
    a = ap.parse_args()

    new = render(a.template.read_text(), read_values(a.values), a.values.name)
    old = a.out.read_text() if a.out.exists() else None
    if old == new:
        print(f"{a.out}: already up to date")
        return 0
    diff = "".join(difflib.unified_diff((old or "").splitlines(True), new.splitlines(True), f"{a.out} (now)", f"{a.out} (generated)"))
    if a.check:
        print(diff or f"{a.out} does not exist")
        return 1
    if not a.apply:
        print(diff or f"would create {a.out}")
        print("Dry run. Add --apply to write it.")
        return 0
    if old is not None:
        shutil.copy2(a.out, a.out.with_name(a.out.name + ".bak"))
    a.out.write_text(new)
    print(f"wrote {a.out}" + (" (previous kept as .bak)" if old is not None else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
